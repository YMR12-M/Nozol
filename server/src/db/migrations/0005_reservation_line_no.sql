--  0005 — رقم «سطر الغرفة» داخل الحجز
--
--  حجز بغرفتين قد يُنقَل نزيل إحداهما لغرفة أخرى في منتصف الإقامة، فيصير
--  لها جزءان متتاليان. line_no يربط أجزاء الغرفة الواحدة معًا (0 للأولى،
--  1 للثانية...) كي نعرف أي جزء يُمدَّد عند إطالة الإقامة وأيّها يُقصَّر.
-- ═══════════════════════════════════════════════════════════════

ALTER TABLE reservation_units
  ADD COLUMN line_no TINYINT UNSIGNED NOT NULL DEFAULT 0 AFTER reservation_id,
  ADD KEY ix_ru_line (reservation_id, line_no, check_in);
